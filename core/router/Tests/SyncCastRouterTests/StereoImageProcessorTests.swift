        XCTAssertEqual(lowGain, 0, accuracy: 0.1)

        // High side: with the band's upper edge pulled down to 2 kHz, a 20 kHz
        // tone is three and a third octaves above it.
        var highSettings = StereoImageSettings()
        highSettings.crosstalk = StereoCrosstalkSettings(
            enabled: true, strength: 1,
            lowHz: StereoImageLimits.crosstalkLowRangeHz.lowerBound, highHz: 2_000

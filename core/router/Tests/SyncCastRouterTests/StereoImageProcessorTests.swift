    // MARK: - Crosstalk stage

    /// Settings with both halves of the band split switched off, so the
    /// recursion can be observed on its own.
    ///
    /// This is a real configuration, not a test hook: the low edge at its
    /// minimum means "no low edge", and a high edge at or above 45% of the
    /// sample rate cannot be realised as a second-order section, so both are
    /// skipped rather than run.
    private func fullBandCrosstalk(attenuationDb: Double = -2.5) -> StereoImageSettings {
        var settings = StereoImageSettings()
        settings.crosstalk = StereoCrosstalkSettings(
            enabled: true,
            attenuationDb: attenuationDb,
            strength: 1,
            lowHz: StereoImageLimits.crosstalkLowRangeHz.lowerBound,
            highHz: StereoImageLimits.crosstalkHighRangeHz.upperBound
        )
        return settings
    }

    func testImpulseInLeftProducesTheRecursiveTail() {
        let settings = fullBandCrosstalk()
        let a = settings.crosstalk.feedbackAmplitude
        let delay = settings.crosstalk.delaySamples(sampleRate: sampleRate)
        XCTAssertEqual(a, pow(10, -2.5 / 20), accuracy: 1e-9)

        let processor = makeProcessor()
        processor.setSettings(settings, pair: 0)

        // The first publish starts a 20 ms crossfade out of the neutral bank,
        // exactly as a live edit would. Let it finish on silence, so what the
        // impulse then measures is the settled recursion and not the fade.
        let frames = 64
        var left = [Float](repeating: 0, count: frames)
        var right = [Float](repeating: 0, count: frames)
        for _ in 0..<Int((sampleRate * 0.04).rounded()) / frames {
            for index in 0..<frames {
                left[index] = 0
                right[index] = 0
            }
            process(processor, left: &left, right: &right, frames: frames)
        }
        for index in 0..<frames {
            left[index] = 0
            right[index] = 0
        }
        left[0] = 1
        process(processor, left: &left, right: &right, frames: frames)

        // Solving the recursion for L = δ, R = 0:
        //   R' has taps at τ, 3τ, 5τ … with −a, −a³, −a⁵
        //   L' has taps at 0, 2τ, 4τ … with  1,  a²,  a⁴
        // τ is 5.49 samples here, so each "tap" is spread over the two (for
        // the first reflection) or three (for the second) samples the linear
        // interpolator touches. The interpolator has unity DC gain, so the
        // AREA of each tap is exact and that is what is asserted.
        let firstWindow = 1...Int((2 * delay).rounded(.down))
        let firstEcho = firstWindow.reduce(0.0) { $0 + Double(right[$1]) }
        XCTAssertEqual(firstEcho, -a, accuracy: 1e-5, "first echo: −a at τ, in the OTHER channel")

        let secondWindow = Int(delay.rounded(.up))...Int((3 * delay).rounded(.down))
        let secondEcho = secondWindow.reduce(0.0) { $0 + Double(left[$1]) }
        XCTAssertEqual(secondEcho, a * a, accuracy: 1e-5, "second echo: +a² at 2τ, back in L")

        XCTAssertEqual(Double(left[0]), 1, accuracy: 1e-6, "the direct sound is untouched")
        // Nothing arrives before the first echo can physically have travelled.
        for index in 1..<Int(delay.rounded(.down)) {
            XCTAssertEqual(Double(right[index]), 0, accuracy: 1e-7)
        }
    }

    func testRecursionIsStableAtTheStrongestLegalSetting() {
        // a = 10^(−1/20) = 0.891 at full strength: the worst case the ranges
        // allow, and the one where an unstable structure would run away.
        let settings = fullBandCrosstalk(attenuationDb: -1)
        let processor = makeProcessor()
        processor.setSettings(settings, pair: 0)

        var generator = SystemRandomNumberGenerator()
        let block = 1_024
        var left = [Float](repeating: 0, count: block)
        var right = [Float](repeating: 0, count: block)
        let noiseBlocks = Int(10 * sampleRate) / block   // 10 seconds

        for _ in 0..<noiseBlocks {
            for index in 0..<block {
                left[index] = Float(Double.random(in: -0.5...0.5, using: &generator))
                right[index] = Float(Double.random(in: -0.5...0.5, using: &generator))
            }
            process(processor, left: &left, right: &right, frames: block)
            for index in 0..<block {
                XCTAssertTrue(left[index].isFinite && right[index].isFinite)
                XCTAssertLessThanOrEqual(abs(left[index]), 1)
                XCTAssertLessThanOrEqual(abs(right[index]), 1)
            }
        }

        // Then a second of silence: a stable structure decays to nothing. A
        // marginally stable or growing one would still be ringing.
        var tailPeak: Float = 0
        for blockIndex in 0..<Int(sampleRate) / block {
            for index in 0..<block {
                left[index] = 0
                right[index] = 0
            }
            process(processor, left: &left, right: &right, frames: block)
            if blockIndex >= 4 {
                for index in 0..<block {
                    tailPeak = max(tailPeak, max(abs(left[index]), abs(right[index])))
                }
            }
        }
        XCTAssertLessThan(tailPeak, 1e-5, "the recursion must decay once the input stops")
    }

    func testBandSplitPassesOutOfBandTonesUnchanged() {
        // Low side: the default band starts at 1500 Hz, so 60 Hz is four and a

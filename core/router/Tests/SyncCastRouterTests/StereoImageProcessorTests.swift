    }

    // MARK: - Bypass fast path

    func testNeutralSettingsLeaveTheBufferBitIdentical() {
        let processor = makeProcessor()
        // Both stages ON but at their no-op values — the case a naive "is the
        // toggle on?" check would get wrong.
        var settings = StereoImageSettings()
        settings.width = StereoWidthSettings(enabled: true, width: 1.0, midTrimDb: 0)
        settings.crosstalk = StereoCrosstalkSettings(enabled: true, strength: 0)
        processor.setSettings(settings, pair: 0)

        let frames = 512
        var left = [Float](repeating: 0, count: frames)
        var right = [Float](repeating: 0, count: frames)
        for index in 0..<frames {
            left[index] = Float(sin(Double(index) * 0.031)) * 0.7
            right[index] = Float(cos(Double(index) * 0.017)) * 0.5
        }
        let expectedLeft = left
        let expectedRight = right
        for _ in 0..<8 {
            var blockLeft = expectedLeft
            var blockRight = expectedRight
            process(processor, left: &blockLeft, right: &blockRight, frames: frames)
            XCTAssertEqual(blockLeft, expectedLeft)
            XCTAssertEqual(blockRight, expectedRight)
        }
        XCTAssertEqual(processor.clipCount, 0)
        XCTAssertFalse(processor.isEngaged)
    }

    func testBypassIsBitIdenticalEvenWithBothStagesDialledIn() {

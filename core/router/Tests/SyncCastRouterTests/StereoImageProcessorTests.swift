    }

    func testCorrelatedContentSeesTheDocumentedColourationPeak() {
        // The recursion's own peak on centred content, `1/(1−a)` at 1/(2τ).
        // Asserted because it is the number the UI warns with and the reason
        // the limiter exists — if the structure ever stopped doing this, the
        // warning would be lying.
        let settings = fullBandCrosstalk()
        let processor = makeProcessor()
        processor.setSettings(settings, pair: 0)
        let peakHz = settings.crosstalk.peakColourationHz
        XCTAssertEqual(peakHz, 4_371, accuracy: 40)
        let gain = measuredGainDb(processor, hz: peakHz) { (sin($0) * 0.1, sin($0) * 0.1) }

        // What is actually measured is a little BELOW the closed-form peak,
        // and by a knowable amount: the linear interpolator in the feedback
        // path has magnitude `sqrt(1 − 2d(1−d)(1−cos ω))` rather than 1, so
        // the effective `a` at the peak frequency is reduced. This is the HF
        // error the fractional-delay choice was made with open eyes, pinned
        // here so a future switch to an allpass interpolator shows up.
        let delay = settings.crosstalk.delaySamples(sampleRate: sampleRate)
        let fraction = delay - delay.rounded(.down)
        let omega = 2 * Double.pi * peakHz / sampleRate
        let interpolator = sqrt(1 - 2 * fraction * (1 - fraction) * (1 - cos(omega)))
        let effective = settings.crosstalk.feedbackAmplitude * interpolator
        XCTAssertEqual(gain, -20 * log10(1 - effective), accuracy: 0.4)
        XCTAssertLessThan(
            gain, settings.crosstalk.peakColourationDb + 0.1,
            "the UI's warning figure must never understate what is heard"
        )
    }


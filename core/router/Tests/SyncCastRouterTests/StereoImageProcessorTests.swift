    func testParameterChangeIsCrossfadedRatherThanStepped() {
        // A 100 Hz side-only tone: its own sample-to-sample step is tiny, so
        // an un-faded coefficient swap would stand out as a large first
        // difference. Compare a run that changes settings mid-stream against
        // one that does not.
        func run(changeAt changeBlock: Int?) -> Double {
            let processor = makeProcessor()
            var settings = StereoImageSettings()
            settings.width = StereoWidthSettings(enabled: true, width: 1.0, cornerHz: 200)
            processor.setSettings(settings, pair: 0)

            let block = 256
            var phase = 0.0
            let increment = 2 * Double.pi * 100 / sampleRate
            var left = [Float](repeating: 0, count: block)
            var right = [Float](repeating: 0, count: block)
            var previous: Float = 0
            var maxStep = 0.0
            for blockIndex in 0..<64 {
                if blockIndex == changeBlock {
                    var changed = settings
                    changed.width.width = 2.0
                    processor.setSettings(changed, pair: 0)
                }
                for index in 0..<block {
                    let value = Float(sin(phase) * 0.4)
                    phase += increment
                    left[index] = value
                    right[index] = -value
                }
                process(processor, left: &left, right: &right, frames: block)
                for index in 0..<block {
                    maxStep = max(maxStep, Double(abs(left[index] - previous)))
                    previous = left[index]
                }
            }
            return maxStep
        }
        let steady = run(changeAt: nil)
        let switched = run(changeAt: 20)
        XCTAssertLessThan(
            switched, steady * 2,
            "a 20 ms crossfade must keep the change below a visible step"
        )
    }

    func testResetAllReturnsEveryPairToNeutral() {
        let processor = StereoImageProcessor(
            pairCount: 3, channelsPerPair: 2, sampleRate: sampleRate
        )
        var settings = StereoImageSettings()
        settings.width = StereoWidthSettings(enabled: true, width: 1.7)
        for pair in 0..<3 { processor.setSettings(settings, pair: pair) }
        XCTAssertTrue(processor.isEngaged)
        processor.resetAll()
        XCTAssertFalse(processor.isEngaged)
    }

    func testOutOfRangePairAndOversizedBlockAreRefusedNotFatal() {
        let processor = makeProcessor()
        var settings = StereoImageSettings()
        settings.width = StereoWidthSettings(enabled: true, width: 1.7)
        XCTAssertFalse(processor.setSettings(settings, pair: 4))
        processor.setSettings(settings, pair: 0)

        // A block longer than the scratch buffers is left alone rather than
        // served from a short buffer.
        let frames = StereoImageProcessor.maxFramesPerBlock + 1
        var left = [Float](repeating: 0.5, count: frames)
        var right = [Float](repeating: -0.5, count: frames)
        let expected = left
        process(processor, left: &left, right: &right, frames: frames)
        XCTAssertEqual(left, expected)
    }

    func testDerivedDelayMatchesTheGeometry() {
        let crosstalk = StereoCrosstalkSettings(enabled: true)
        // span·ear/distance / c = 0.17·0.15/0.65 / 343 ≈ 114 µs.
        XCTAssertEqual(crosstalk.delaySeconds, 114.4e-6, accuracy: 1e-6)
        XCTAssertEqual(crosstalk.delaySamples(sampleRate: 48_000), 5.49, accuracy: 0.02)
        // Halving the distance doubles the path difference and so the delay.
        var nearer = crosstalk
        nearer.distanceMeters = 0.325
        XCTAssertEqual(nearer.delaySeconds, 2 * crosstalk.delaySeconds, accuracy: 1e-9)
    }

    func testDelayIsHeldAtOneWholeSampleForExtremeGeometry() {
        // The recursion reads its own past output; a delay below one sample
        // would need the sample being computed.
        var crosstalk = StereoCrosstalkSettings(enabled: true)
        crosstalk.spanMeters = 0.05
        crosstalk.distanceMeters = 3.0
        XCTAssertLessThan(crosstalk.delaySeconds * 48_000, 1)
        XCTAssertEqual(crosstalk.delaySamples(sampleRate: 48_000), 1)
    }

    func testFeedbackStaysStrictlyInsideTheUnitCircle() {
        for db in stride(from: -6.0, through: -1.0, by: 0.25) {

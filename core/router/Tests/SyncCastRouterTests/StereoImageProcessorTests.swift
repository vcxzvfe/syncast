            crosstalk.attenuationDb = db
            crosstalk.strength = 1
            XCTAssertLessThan(
                crosstalk.feedbackAmplitude, 1,
                "|a| < 1 is the stability condition, at every legal attenuation"
            )
        }
    }

    func testSanitizationClampsGarbageAndKeepsTheBandOrdered() {
        var settings = StereoImageSettings()
        settings.width.enabled = true
        settings.width.width = 99
        settings.width.cornerHz = .nan
        settings.width.midTrimDb = -40
        settings.crosstalk.enabled = true
        settings.crosstalk.attenuationDb = 12
        settings.crosstalk.strength = .infinity
        settings.crosstalk.spanMeters = -3
        settings.crosstalk.lowHz = 4_000
        settings.crosstalk.highHz = 2_000
        let clean = settings.sanitized()
        XCTAssertEqual(clean.width.width, 2)
        XCTAssertEqual(clean.width.cornerHz, StereoImageLimits.defaultWidthCornerHz)
        XCTAssertEqual(clean.width.midTrimDb, -1)
        XCTAssertEqual(clean.crosstalk.attenuationDb, -1)
        XCTAssertEqual(clean.crosstalk.strength, StereoImageLimits.defaultStrength)
        XCTAssertEqual(clean.crosstalk.spanMeters, 0.05)
        XCTAssertGreaterThan(
            clean.crosstalk.highHz, clean.crosstalk.lowHz,
            "an inverted band would make the split filters fight each other"
        )
    }

    func testCodableRoundTripSurvivesAMissingField() throws {

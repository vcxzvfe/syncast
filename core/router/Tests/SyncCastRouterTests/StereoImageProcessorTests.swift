    // MARK: - Width stage

    func testPureMidSignalIsUnchangedAtAnyWidth() {
        // L == R means S == 0, and the stage only ever scales S. This is the
        // mono-compatibility property, asserted at the sample level rather
        // than argued for in a comment.
        for width in [0.0, 0.5, 1.4, 2.0] {
            let processor = makeProcessor()
            var settings = StereoImageSettings()
            settings.width = StereoWidthSettings(
                enabled: true, width: width, cornerHz: 1_500, midTrimDb: 0
            )
            processor.setSettings(settings, pair: 0)

            let frames = 1_024
            var left = [Float](repeating: 0, count: frames)
            for index in 0..<frames {
                left[index] = Float(sin(Double(index) * 0.09) * 0.4)
            }
            var right = left
            let expected = left
            process(processor, left: &left, right: &right, frames: frames)
            XCTAssertEqual(left, expected, "width \(width) moved a mono signal")
            XCTAssertEqual(right, expected, "width \(width) moved a mono signal")
        }
    }

    func testSideSignalScalesByWidthAboveTheCorner() {
        let width = 1.4
        var settings = StereoImageSettings()
        settings.width = StereoWidthSettings(enabled: true, width: width, cornerHz: 1_500)

        // Well above the corner the side high-pass is asymptotically unity, so
        // the achieved gain is the width itself.
        let far = makeProcessor()
        far.setSettings(settings, pair: 0)
        let farGain = measuredGainDb(far, hz: 9_600) { (sin($0) * 0.3, -sin($0) * 0.3) }
        XCTAssertEqual(farGain, 20 * log10(width), accuracy: 0.2)

        // One octave above a second-order corner the high-pass is at 0.97 with
        // 43° of phase, so `S + (width−1)·HP(S)` lands a little short of the
        // full width. That shortfall is the documented cost of leaving the
        // side signal untouched below the corner rather than crossing it over.
        let near = makeProcessor()
        near.setSettings(settings, pair: 0)
        let nearGain = measuredGainDb(near, hz: 3_000) { (sin($0) * 0.3, -sin($0) * 0.3) }
        XCTAssertEqual(nearGain, 20 * log10(width), accuracy: 0.7)
        XCTAssertGreaterThan(nearGain, 1.0, "3 kHz must already be well into the widened band")
    }

    func testSideSignalIsUntouchedBelowTheCorner() {
        var settings = StereoImageSettings()
        settings.width = StereoWidthSettings(enabled: true, width: 1.4, cornerHz: 1_500)
        let processor = makeProcessor()

import XCTest
@testable import SyncCastRouter

/// Settings validation, the derived geometry, and the real-time processor's
/// observable behaviour.
///
/// Everything here is offline: buffers are pushed through
/// `StereoImageProcessor` exactly the way `LocalOutput.render()` does, so a
/// regression in the DSP shows up without a CoreAudio device. The claims that
/// need a listener (does it actually widen the image?) are the user's to
/// judge; what is pinned here is that the maths does what the maths is
/// supposed to do.
final class StereoImageProcessorTests: XCTestCase {

    private let sampleRate: Double = 48_000

    // MARK: - Harness

    /// Push one block through the processor the way the render callback does.
    private func process(
        _ processor: StereoImageProcessor,
        left: inout [Float],
        right: inout [Float],
        frames: Int,
        pair: Int = 0
    ) {
        left.withUnsafeMutableBufferPointer { leftBuffer in
            right.withUnsafeMutableBufferPointer { rightBuffer in
                var pointers = [leftBuffer.baseAddress!, rightBuffer.baseAddress!]
                pointers.withUnsafeMutableBufferPointer { table in
                    processor.process(
                        pair: pair,
                        channels: table.baseAddress!,
                        channelOffset: 0,
                        channelCount: 2,
                        frames: frames
                    )
                }
            }
        }
    }

    /// Steady-state gain applied to a stereo signal generated by `sample`,
    /// measured as output RMS over input RMS on the left channel.
    ///
    /// This measures the SHIPPING code path (`process`), not the coefficient
    /// formulas, which is the point.
    private func measuredGainDb(
        _ processor: StereoImageProcessor,
        hz: Double,
        sample: (Double) -> (Double, Double),
        settleFrames: Int = 48_000,
        measureFrames: Int = 48_000
    ) -> Double {
        var inputSquares = 0.0
        var outputSquares = 0.0
        var phase = 0.0
        let increment = 2 * Double.pi * hz / sampleRate
        let block = 512
        var produced = 0
        let total = settleFrames + measureFrames

        var left = [Float](repeating: 0, count: block)
        var right = [Float](repeating: 0, count: block)
        var reference = [Double](repeating: 0, count: block)

        while produced < total {
            let frames = min(block, total - produced)
            for index in 0..<frames {
                let (l, r) = sample(phase)
                phase += increment
                reference[index] = l
                left[index] = Float(l)
                right[index] = Float(r)
            }
            process(processor, left: &left, right: &right, frames: frames)
            if produced >= settleFrames {
                for index in 0..<frames {
                    inputSquares += reference[index] * reference[index]
                    outputSquares += Double(left[index]) * Double(left[index])
                }
            }
            produced += frames
        }
        guard inputSquares > 0 else { return 0 }
        return 20 * log10(sqrt(outputSquares / inputSquares))
    }

    private func makeProcessor() -> StereoImageProcessor {
        StereoImageProcessor(pairCount: 1, channelsPerPair: 2, sampleRate: sampleRate)
    }

